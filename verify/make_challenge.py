"""Generate the Comparator challenge (trusted statement files) from the library.

For every file EconLean/X.lean (except the hand-written EconLean/Audit/), writes
challenge/EconLean/X.lean with comments stripped and theorem proofs replaced by
`sorry`. `challenge/` is a separate Lake project using the SAME module names as
the library: Lean bakes module names into auxiliary declarations (e.g. the
private `_proof_N` lemmas inside a `def`), so a challenge under a different
module name would never match a definition that contains a tactic proof.
It shares Mathlib with the main project via `packagesDir`.

Also writes comparator.json listing every public theorem.

The output is meant to be REVIEWED and COMMITTED: it is the frozen,
adversarially-reviewed statement of what the library claims. verify/check.sh
regenerates it and fails on any diff, so a statement cannot change without the
challenge diff showing up in review.

Usage (from repo root): python3 verify/make_challenge.py
"""
import json, pathlib, re, shutil, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from strip_proofs import strip_comments, strip_proofs, DECL

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIB = 'EconLean'
SRC = ROOT / LIB
CH = ROOT / 'challenge'
SKIP = {'Audit'}  # hand-written audit files (restatements, findings), not library results

def theorem_names(text):
    """Fully qualified public theorem names, tracking namespace/section blocks."""
    stack, names = [], []
    for line in text.split('\n'):
        m = re.match(r'^(?:@\[[^\]]*\]\s*)?(?:noncomputable\s+|public\s+|private\s+)*(namespace|section)\b\s*(\S*)', line)
        if m:
            stack.append((m.group(1), m.group(2))); continue
        if re.match(r'^end\b', line):
            if stack: stack.pop()
            continue
        if DECL.match(line):
            if re.search(r'\bprivate\b', re.split(r'\b(?:theorem|lemma)\b', line)[0]):
                continue  # private names are mangled and not part of the public API
            n = re.search(r'\b(?:theorem|lemma)\s+(\S+)', line).group(1)
            ns = [s for k, s in stack if k == 'namespace' and s]
            names.append('.'.join(ns + [n]))
    return names

def main():
    if (CH / LIB).exists():
        shutil.rmtree(CH / LIB)
    names = []
    for f in sorted(SRC.rglob('*.lean')):
        if f.relative_to(SRC).parts[0] in SKIP:
            continue
        t = strip_proofs(strip_comments(f.read_text()))
        o = CH / LIB / f.relative_to(SRC); o.parent.mkdir(parents=True, exist_ok=True)
        o.write_text('-- AUTO-GENERATED by verify/make_challenge.py. Review diffs; do not hand-edit.\n' + t.lstrip())
        names += theorem_names(t)
    root = (ROOT / f'{LIB}.lean').read_text()
    root = '\n'.join(l for l in root.split('\n') if not re.match(rf'^(public )?import {LIB}\.Audit\b', l))
    (CH / f'{LIB}.lean').write_text(root)
    lakefile = (ROOT / 'lakefile.toml').read_text()
    lakefile = lakefile.replace('defaultTargets', 'packagesDir = "../.lake/packages"\ndefaultTargets', 1)
    (CH / 'lakefile.toml').write_text('# AUTO-GENERATED by verify/make_challenge.py\n' + lakefile)
    shutil.copy(ROOT / 'lean-toolchain', CH / 'lean-toolchain')
    manifest = json.loads((ROOT / 'lake-manifest.json').read_text())
    manifest['packagesDir'] = '../.lake/packages'  # share the main project's built Mathlib
    (CH / 'lake-manifest.json').write_text(json.dumps(manifest, indent=1) + '\n')
    (CH / '.gitignore').write_text('.lake/\n')
    cfg = {"challenge_module": LIB, "solution_module": LIB,
           "theorem_names": names,
           "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"]}
    (ROOT / 'comparator.json').write_text(json.dumps(cfg, indent=2) + '\n')
    print(f'{len(names)} theorems written to comparator.json')

if __name__ == '__main__':
    main()
